package ru.tac.whosayswhat.audio

/**
 * Минимум, который крупный план животного висит на экране. Короткая запись
 * («Мяу!») длится меньше секунды: без этой границы увеличение мигало бы, и
 * ребёнок не успел бы рассмотреть животное.
 */
internal const val SPOTLIGHT_MIN_MS = 2_500L

/**
 * Хвост после конца записи: озвучка названия начинается с небольшой паузы,
 * и картинка не должна исчезнуть ровно на её первом слоге.
 */
internal const val SPOTLIGHT_TAIL_MS = 300L

/**
 * Сколько сверх нижней границы ждём конца фразы синтезатора речи. Фраза
 * «Это кошечка!» на замедленной речи укладывается в две секунды; четыре —
 * запас на медленный голос и на движок, который вообще не пришлёт колбэк.
 */
internal const val SPOTLIGHT_NARRATION_BUDGET_MS = 4_000L

/**
 * Сколько держать крупный план минимум, если запись длится [soundMs].
 *
 * Нижняя граница нужна, чтобы увеличение не мигало на коротком звуке, а
 * верхняя привязана к длительности записи: длинный звук не должен обрывать
 * картинку на середине.
 */
internal fun spotlightFloorMs(soundMs: Long): Long =
    (if (soundMs > 0L) soundMs + SPOTLIGHT_TAIL_MS else SPOTLIGHT_MIN_MS)
        .coerceAtLeast(SPOTLIGHT_MIN_MS)

/**
 * Предел ожидания фразы синтезатора речи. Если колбэк о конце фразы так и не
 * пришёл, крупный план закрывается сам — иначе увеличенная картинка осталась
 * бы поверх песочницы, и вернуться к животным было бы нельзя.
 */
internal fun spotlightMaxWaitMs(floorMs: Long): Long =
    floorMs + SPOTLIGHT_NARRATION_BUDGET_MS
